import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const TEST_DIR = path.dirname(fileURLToPath(import.meta.url));
const SCRIPT = path.resolve(TEST_DIR, '..', '..', 'scripts', 'harness', 'check-generated.mjs');

const MARKER = 'Code generated by pantheon low-code generator. DO NOT EDIT.';
const MARKED = [
  'backend/modules/business/generated_registry.go',
  'backend/modules/system/iam/menu/generated_component_registry.go',
  'frontend/src/modules/generated/business.ts',
  'frontend/src/modules/generated/system.ts',
  'frontend/src/core/router/generatedComponentRegistry.ts',
  'frontend/src/i18n/resources/generated/zh-CN.ts',
  'frontend/src/i18n/resources/generated/en-US.ts',
  'frontend/src/i18n/resources/generated/ko-KR.ts',
  'frontend/src/i18n/resources/generated/ja-JP.ts',
  'frontend/src/i18n/resources/generated/fr-FR.ts',
];

function createRoot() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'generated-check-'));
  const write = (relative, content) => {
    const full = path.join(root, relative);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
  };
  for (const relative of MARKED) {
    write(relative, `// ${MARKER}\n\nexport const x = {};\n`);
  }
  write('schema/generated/feature-ledger.json', JSON.stringify({ version: 1, entries: [] }));
  return { root, write };
}

function run(root, extra = []) {
  return spawnSync(process.execPath, [SCRIPT, '--json', '--strict', '--root', root, ...extra], { encoding: 'utf8' });
}

test('passes when every artifact carries the first-line marker', () => {
  const { root } = createRoot();
  const result = run(root);
  assert.equal(result.status, 0, result.stdout);
  assert.equal(JSON.parse(result.stdout).findingCount, 0);
});

test('flags a generated artifact missing its marker', () => {
  const { root, write } = createRoot();
  write('frontend/src/modules/generated/business.ts', "import type { ModuleConfig } from '../../core/router/types';\n");
  const result = run(root);
  assert.equal(result.status, 1);
  const body = JSON.parse(result.stdout);
  assert.equal(body.findings[0].rule, 'generated-marker-missing');
});

test('flags a marker that is not the first line', () => {
  const { root, write } = createRoot();
  write('frontend/src/core/router/generatedComponentRegistry.ts', `\n// ${MARKER}\nexport const x = {};\n`);
  const result = run(root);
  assert.equal(result.status, 1);
  assert.equal(JSON.parse(result.stdout).findings[0].rule, 'generated-marker-not-first-line');
});

test('flags a missing generated artifact', () => {
  const { root } = createRoot();
  fs.rmSync(path.join(root, 'backend/modules/business/generated_registry.go'));
  const result = run(root);
  assert.equal(result.status, 1);
  assert.equal(JSON.parse(result.stdout).findings[0].rule, 'generated-artifact-missing');
});

test('flags an unparseable generated JSON artifact', () => {
  const { root, write } = createRoot();
  write('schema/generated/feature-ledger.json', '{ not json');
  const result = run(root);
  assert.equal(result.status, 1);
  assert.equal(JSON.parse(result.stdout).findings[0].rule, 'generated-artifact-invalid');
});

test('report-only mode exits 0 even with findings', () => {
  const { root, write } = createRoot();
  write('frontend/src/modules/generated/business.ts', 'no marker\n');
  const result = spawnSync(process.execPath, [SCRIPT, '--root', root], { encoding: 'utf8' });
  assert.equal(result.status, 0);
  assert.match(result.stdout, /finding\(s\)/);
});

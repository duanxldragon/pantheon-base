#!/usr/bin/env node

/**
 * Mechanical gate for generated artifacts.
 * Contract source: docs/designs/REPOSITORY_LAYOUT.md §7.
 *
 * Every generated artifact must be identifiable by a stable first-line marker so
 * a manual edit (or a hand-written registry) is detectable. The matching reset
 * templates live in frontend/scripts/cleanup-generated-modules.mjs — keep the
 * marker string and the artifact list in sync with that script and with
 * REPOSITORY_LAYOUT.md §7.2.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const DEFAULT_ROOT = process.cwd();

const GENERATED_MARKER = 'Code generated by pantheon low-code generator. DO NOT EDIT.';
const MARKER_LINE = `// ${GENERATED_MARKER}`;

// Text artifacts that must carry the marker on their first line.
const MARKED_ARTIFACTS = [
  'backend/modules/business/generated_registry.go',
  'backend/modules/system/iam/menu/generated_component_registry.go',
  'frontend/src/modules/generated/business.ts',
  'frontend/src/modules/generated/system.ts',
  'frontend/src/core/router/generatedComponentRegistry.ts',
  'frontend/src/i18n/resources/generated/zh-CN.ts',
  'frontend/src/i18n/resources/generated/en-US.ts',
  'frontend/src/i18n/resources/generated/ko-KR.ts',
  'frontend/src/i18n/resources/generated/ja-JP.ts',
  'frontend/src/i18n/resources/generated/fr-FR.ts',
];

// JSON artifacts cannot carry a comment marker; they are identified by path and
// shape instead.
const JSON_ARTIFACTS = ['schema/generated/feature-ledger.json'];

function parseArgs(argv) {
  const options = { json: false, strict: false, help: false, root: DEFAULT_ROOT };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--json') options.json = true;
    else if (arg === '--strict') options.strict = true;
    else if (arg === '--help' || arg === '-h') options.help = true;
    else if (arg === '--root') {
      const value = argv[index + 1];
      if (!value) throw new Error('--root requires a path');
      options.root = path.resolve(value);
      index += 1;
    } else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

function printHelp() {
  console.log('Usage: node scripts/harness/check-generated.mjs [--json] [--strict] [--root <path>]');
  console.log('Checks that generated artifacts exist and carry the stable generated marker.');
}

function checkMarkedArtifact(root, relativePath) {
  const absolute = path.join(root, relativePath);
  if (!fs.existsSync(absolute)) {
    return { file: relativePath, rule: 'generated-artifact-missing', reason: 'generated artifact does not exist; regenerate or restore it' };
  }
  const content = fs.readFileSync(absolute, 'utf8');
  const firstLine = content.split(/\r?\n/, 1)[0];
  if (firstLine === MARKER_LINE) {
    return null;
  }
  if (content.includes(GENERATED_MARKER)) {
    return { file: relativePath, rule: 'generated-marker-not-first-line', reason: 'the generated marker must be the first line of the file' };
  }
  return { file: relativePath, rule: 'generated-marker-missing', reason: `missing generated marker: "${MARKER_LINE}"` };
}

function checkJsonArtifact(root, relativePath) {
  const absolute = path.join(root, relativePath);
  if (!fs.existsSync(absolute)) {
    return { file: relativePath, rule: 'generated-artifact-missing', reason: 'generated artifact does not exist; regenerate or restore it' };
  }
  try {
    JSON.parse(fs.readFileSync(absolute, 'utf8'));
    return null;
  } catch (error) {
    return { file: relativePath, rule: 'generated-artifact-invalid', reason: `generated JSON is not parseable: ${error.message}` };
  }
}

function main() {
  let options;
  try {
    options = parseArgs(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    return 1;
  }
  if (options.help) return printHelp(), 0;

  const findings = [];
  for (const relativePath of MARKED_ARTIFACTS) {
    const finding = checkMarkedArtifact(options.root, relativePath);
    if (finding) findings.push(finding);
  }
  for (const relativePath of JSON_ARTIFACTS) {
    const finding = checkJsonArtifact(options.root, relativePath);
    if (finding) findings.push(finding);
  }

  if (options.json) {
    console.log(
      JSON.stringify(
        { mode: options.strict ? 'strict' : 'report-only', checkedCount: MARKED_ARTIFACTS.length + JSON_ARTIFACTS.length, findingCount: findings.length, findings },
        null,
        2,
      ),
    );
  } else {
    console.log(
      `Generated artifact check (${options.strict ? 'strict' : 'report-only'}): ${findings.length} finding(s) across ${MARKED_ARTIFACTS.length + JSON_ARTIFACTS.length} artifact(s)`,
    );
    for (const finding of findings) {
      console.log(`finding: ${finding.file} [${finding.rule}]`);
      console.log(`  reason: ${finding.reason}`);
    }
  }

  return options.strict && findings.length > 0 ? 1 : 0;
}

process.exitCode = main();
